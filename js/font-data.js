// ── Row-string glyph helper: { A: ['.#.', '#.#', ...] } → { A: [0,1,0, 1,0,1, ...] }
function glyphsFromRows(map) {
  return Object.fromEntries(Object.entries(map).map(([ch, rows]) =>
    [ch, rows.join('').split('').map(c => (c === '#' ? 1 : 0))]));
}

/**
 * "Squarify" a glyph: fill rounded outer corners. An OFF pixel is filled when two
 * orthogonal ON neighbours form an L whose arms both continue away from it, the
 * diagonal between them is OFF and its other two neighbours are OFF. Inner counter
 * corners (like the inside of 'o') fail the "arms continue" test and stay open.
 */
function squarifyGlyph(data, cols, rows) {
  const on = (c, r) => c >= 0 && c < cols && r >= 0 && r < rows && data[r * cols + c] === 1;
  const out = [...data];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      if (on(c, r)) continue;
      for (const [dx, dy] of [[1, 1], [-1, 1], [1, -1], [-1, -1]]) {
        if (on(c + dx, r) && on(c + 2 * dx, r) &&
            on(c, r + dy) && on(c, r + 2 * dy) &&
            !on(c + dx, r + dy) && !on(c - dx, r) && !on(c, r - dy)) {
          out[r * cols + c] = 1;
          break;
        }
      }
    }
  }
  return out;
}

/**
 * Pixel italic from a 4-wide glyph: top 3 rows shift right one column into a
 * 5-wide grid, the rest stay put.
 */
function italicizeGlyph(data, srcCols, rows) {
  const dstCols = srcCols + 1;
  const out = new Array(dstCols * rows).fill(0);
  for (let r = 0; r < rows; r++) {
    const shift = r < 3 ? 1 : 0;
    for (let c = 0; c < srcCols; c++) out[r * dstCols + c + shift] = data[r * srcCols + c];
  }
  return out;
}

